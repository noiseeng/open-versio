	constexpr static isv_h750 irq2isv(irq_h750 irq)
	{ return arm_irq2isv<isv_h750>(irq); }

	static_assert(irq2isv(irq_h750::NON_MASKABLE_INT) == isv_h750::NMI);
	static_assert(irq2isv(irq_h750::WWDG) == isv_h750::WWDG);
	static_assert((int)isv_h750::WWDG == 16);
	static_assert(irq2isv(irq_h750::TIM2) == isv_h750::TIM2);

